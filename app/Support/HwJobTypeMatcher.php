<?php

namespace App\Support;

/**
 * ハローワーク求人の職種名(例:「介護職員【介護福祉士】屋宜原病院」)から、サイトの職種(master_job_types.name)を決める。
 * 上から順に判定し、最初に当てはまったものを使う。最後の「介護」は「介護職員（施設）」への受け皿。
 */
class HwJobTypeMatcher
{
    public const MAP = [
        '介護福祉士'         => '介護福祉士',
        'ケアマネ'           => 'ケアマネジャー（介護支援専門員）',
        '介護支援専門員'     => 'ケアマネジャー（介護支援専門員）', // 正式名。以前は「介護」に吸われて介護職員になっていた
        'サービス提供責任者' => 'サービス提供責任者',                 // 「訪問介護」より先に判定する
        'サ責'               => 'サービス提供責任者',
        '訪問介護'           => 'ホームヘルパー（訪問介護員）',
        'ヘルパー'           => 'ホームヘルパー（訪問介護員）',
        '生活相談'           => '生活相談員',
        '保育士'             => '保育士',
        '児童指導員'         => '児童指導員',
        '生活支援員'         => '生活支援員',
        '就労支援'           => '就労支援員',
        'サービス管理'       => 'サービス管理責任者（サビ管）',
        '社会福祉士'         => '社会福祉士',
        '精神保健'           => '精神保健福祉士（PSW）',
        '相談支援'           => '相談支援専門員',
        '看護師'             => '看護師（福祉施設勤務）',
        '理学療法士'         => '理学療法士（PT）',
        '作業療法士'         => '作業療法士（OT）',
        '言語聴覚士'         => '言語聴覚士（ST）',
        '栄養士'             => '管理栄養士（施設）',
        '介護事務'           => '介護事務',
        '医療事務'           => '医療事務',
        '介護'               => '介護職員（施設）',
        '看護'               => '看護師（福祉施設勤務）', // 「看護職員」など。「介護・看護職員」は介護職員を優先
    ];

    /** 職種名(master_job_types.name)を返す。当てはまらなければ null */
    public static function match(string $jobTitle): ?string
    {
        foreach (self::MAP as $keyword => $name) {
            if (str_contains($jobTitle, $keyword)) {
                return $name;
            }
        }
        return null;
    }
}
